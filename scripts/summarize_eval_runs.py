#!/usr/bin/env python3
"""Writes docs/ontology/eval_runs_table.md: every scoring run, extraction run and prompt
experiment saved under backups/eval_runs/ as tables, so that the numbers behind
docs/ontology/extraction_quality_findings.md survive in the repository (backups/ is not
committed). Reads only the saved JSON; no LLM call, no database.

    scripts/summarize_eval_runs.py [--runs backups/eval_runs] [--out docs/ontology/eval_runs_table.md]

Run it again after new runs and commit the result. What each document version is (which group
size, which prompt, which schema) is not in the report files, so it is kept in VERSION_NOTES
below: add a line there when a new version is made.
"""

import argparse
import glob
import json
import os
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

DOCS = {"올백": "allbaek", "파워즉시연금": "annuity", "안심종신": "ansim"}

# What each version of a measured document is. 12,000 / 6,000 / 3,000 / 1,500 are the extract chunk-group size.
VERSION_NOTES = {
    ("allbaek", 3): "schema v3, extracted at 12,000 (the original graph)",
    ("allbaek", 4): "extracted at 3,000 (run 1)",
    ("allbaek", 5): "extracted at 6,000",
    ("allbaek", 6): "extracted at 1,500",
    ("allbaek", 7): "extracted at 3,000 (run 2) -- the baseline of the later experiments",
    ("allbaek", 8): "v7 with the level-1 merge mapping, graph relabelled (no re-extraction)",
    ("allbaek", 9): "level-1 simplified schema, extracted again at 3,000",
    ("allbaek", 10): "v7 schema, extracted at 3,000 with the clause-coverage rules (V1)",
    ("annuity", 2): "extracted at 12,000",
    ("annuity", 3): "extracted at 3,000 -- the baseline of the later experiments",
    ("annuity", 4): "v3 with the level-1 merge mapping, graph relabelled (no re-extraction)",
    ("annuity", 5): "level-1 simplified schema, extracted again at 3,000",
    ("annuity", 6): "v3 schema, extracted at 3,000 with the clause-coverage rules (V1); same graph as v7",
    ("annuity", 7): "v3 schema, extracted at 3,000 with the clause-coverage rules (V1), from the resume cache",
}

# The answer reading ignored a node's quoted evidence until this time (docs/ontology/golden_set_evaluation.md, 5-2).
EVIDENCE_FIX = "20261016_120000"


def short_doc(stem: str) -> str:
    return next((key for name, key in DOCS.items() if name in stem), "?")


def stamp(path: str) -> str:
    name = os.path.basename(path)
    digits = [p for p in name.replace(".json", "").split("_") if p.isdigit()]
    return "_".join(digits[-2:])


def pct(x) -> str:
    return "-" if x is None else f"{100 * x:.0f}%"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--runs", default=str(REPO / "backups" / "eval_runs"))
    parser.add_argument("--out", default=str(REPO / "docs" / "ontology" / "eval_runs_table.md"))
    args = parser.parse_args()

    files = sorted(glob.glob(os.path.join(args.runs, "*.json")))
    scoring, records, experiments = [], [], []
    for path in files:
        data = json.loads(Path(path).read_text())
        name = os.path.basename(path)
        if name.startswith("run_"):
            records.append((path, data))
        elif name.startswith("prompt_variant_"):
            experiments.append((path, data))
        elif "summary" in data and "questions" in data:
            scoring.append((path, data))

    out = [
        "# Evaluation runs",
        "",
        "Generated by `scripts/summarize_eval_runs.py` from `backups/eval_runs/` (not committed). Do not edit by hand: run",
        "`make eval-summary` after new runs. Method and findings: `docs/ontology/golden_set_evaluation.md` and",
        "`docs/ontology/extraction_quality_findings.md`. Documents: **allbaek** = 삼성올백(ALL100)종신보험 (224,227 chars,",
        "golden set of 50, 38 answerable-scored), **annuity** = 삼성파워즉시연금보험 (152,395 chars, golden set of 50, 45 scored).",
        "",
        "## Scoring runs",
        "",
        "`answer` is the share of scored questions whose answer facts are in the context the search returned (the reading to",
        "trust); `strict` and `semantic` are the evidence-based readings; `judge` is the LLM verdict when it was asked for.",
        "Rows marked **pre-fix** used an answer reading that left a node's quoted evidence out of the text (fixed 2026-10-16):",
        "their `answer` is too low and is not comparable with later rows. Misses: `extr` = the facts are not in the graph,",
        "`retr` = in the graph but not retrieved.",
        "",
        "| doc | v | time | note | label | nodes | edges | strict | semantic | **answer** | extr | retr | judge | rule |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for path, d in scoring:
        doc = short_doc(d["stem"])
        s, a = d["summary"], d["summary"].get("answer")
        if a is None:
            continue
        sem = s.get("semantic")
        judge = s.get("judge")
        rule = "pre-fix" if stamp(path) < EVIDENCE_FIX else "ok"
        judge_cell = f"{judge['answerable']}/{judge['scored']}" if judge else "-"
        out.append(
            f"| {doc} | {d['version']} | {stamp(path)} | {VERSION_NOTES.get((doc, d['version']), '')} | {d['options'].get('label') or ''} "
            f"| {s['graph']['nodes']} | {s['graph']['edges']} | {pct(s['hit_rate'])} | {pct(sem['hit_rate']) if sem else '-'} "
            f"| **{a['outcomes']['hit']}/{a['scored']} ({pct(a['hit_rate'])})** | {a['outcomes']['extraction_miss']} "
            f"| {a['outcomes']['retrieval_miss']} | {judge_cell} | {rule} |"
        )

    out += [
        "",
        "## Extraction and schema runs",
        "",
        "From the run records (`run_*.json`): wall time, LLM calls, tokens and the model. A run that failed is listed with its",
        "error; its calls were not wasted (finished chunk groups are reused when the command is run again).",
        "",
        "| doc | script | time | new v | from v | group chars | variant | seconds | LLM calls | tokens in / out | nodes | model | failed |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for path, d in records:
        m = d.get("meta", {})
        doc = short_doc(m.get("stem", ""))
        models = ", ".join(x for x in d["llm"]["models"] if "embedding" not in x) or "-"
        out.append(
            f"| {doc} | {d['script']} | {stamp(path)} | {m.get('new_version', m.get('version', ''))} | {m.get('copied_from_version', '')} "
            f"| {m.get('group_chars', d['settings'].get('EXTRACT_GROUP_CHARS', ''))} | {(m.get('variant') or '').split('/')[-1]} "
            f"| {d['elapsed_seconds']:.0f} | {d['llm']['calls']} | {d['llm']['input_tokens']:,} / {d['llm']['output_tokens']:,} "
            f"| {m.get('nodes', '')} | {models} | {(d.get('failed') or '')[:70]} |"
        )

    out += [
        "",
        "## Prompt experiments (the chunks of questions the extraction missed)",
        "",
        "Each cell: questions of the probed set whose answer facts are in the new nodes. `control` is the unchanged prompt run",
        "twice (the run-to-run noise). Only experiments saved in the arms format are listed.",
        "",
        "| doc | time | questions | " + " | ".join(["arm 1", "arm 2", "arm 3", "arm 4"]) + " |",
        "|---|---|---|---|---|---|---|",
    ]
    for path, d in experiments:
        if "arms" not in d:
            continue
        doc = short_doc(d["run"]["meta"]["stem"])
        cells = [f"{name.replace('extract_clause_coverage', 'V1 coverage')}: {sum(1 for q in a['questions'] if q['answer'])}" for name, a in d["arms"].items()]
        cells += [""] * (4 - len(cells))
        out.append(f"| {doc} | {stamp(path)} | {len(d['questions'])} | " + " | ".join(cells[:4]) + " |")

    out += ["", f"_{len(scoring)} scoring runs, {len(records)} run records, {len(experiments)} prompt experiments; generated {datetime.now():%Y-%m-%d}._", ""]
    Path(args.out).write_text("\n".join(out))
    print(f"wrote {args.out}: {len(scoring)} scoring runs, {len(records)} run records, {len(experiments)} experiments")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
